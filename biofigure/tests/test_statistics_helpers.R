args <- commandArgs(trailingOnly=TRUE)
root <- normalizePath(if(length(args)) args[1] else '.',mustWork=TRUE)
source(file.path(root,'scripts/statistics_helpers.R'))
checks <- 0L
check <- function(expr) {stopifnot(expr); checks <<- checks+1L}
rejected <- function(expr) tryCatch({force(expr);FALSE},error=function(e) TRUE)
set.seed(20260928)
d <- data.frame(id=paste0('u',1:24),group=rep(c('control','treated'),each=12),
                y=c(rnorm(12,0,1),rnorm(12,2,2)))
a <- bf_welch_contrast(d,'y','group','id','treated','control')
b <- bf_welch_contrast(d,'y','group','id','control','treated')
check(abs(a$estimate - (mean(d$y[d$group=='treated'])-mean(d$y[d$group=='control'])))<1e-12)
check(abs(a$estimate+b$estimate)<1e-12 && abs(a$p_raw-b$p_raw)<1e-12)
check(a$ci_low<a$estimate && a$ci_high>a$estimate && a$n_lhs==12)
bad<-d;bad$id[2]<-bad$id[1];check(rejected(bf_welch_contrast(bad,'y','group','id','treated','control')))
bad<-d;bad$y[1]<-Inf;check(rejected(bf_welch_contrast(bad,'y','group','id','treated','control')))
id<-paste0('p',1:10); baseline<-rnorm(10,0,1); change<-seq(0.2,2,length.out=10)
pair<-data.frame(id=rep(id,2),condition=rep(c('pre','post'),each=10),y=c(baseline,baseline+change))
shuffled<-pair[sample(nrow(pair)),]
z<-bf_paired_contrast(shuffled,'y','condition','id','post','pre')
check(abs(z$estimate-mean(change))<1e-12 && z$df==9)
check(rejected(bf_paired_contrast(pair[-1,],'y','condition','id','post','pre')))
check(rejected(bf_paired_contrast(rbind(pair,pair[1,]),'y','condition','id','post','pre')))
ir<-iris;ir$id<-seq_len(nrow(ir))
w<-bf_oneway_test(ir,'Sepal.Length','Species','id','welch')
check(w$p_raw<0.001 && w$n_units==150 && is.finite(w$df_denominator))
equal<-bf_oneway_test(ir,'Sepal.Length','Species','id','equal_variance')
means<-tapply(ir$Sepal.Length,ir$Species,mean); grand<-mean(ir$Sepal.Length)
between<-sum(table(ir$Species)*(means-grand)^2)/2
within<-sum((ir$Sepal.Length-means[as.character(ir$Species)])^2)/147
check(abs(equal$statistic-between/within)<1e-10)
standard<-stats::aov(Sepal.Length ~ Species,data=ir)
tukey<-stats::TukeyHSD(standard)$Species
check(nrow(tukey)==3 && all(tukey[,'lwr']<tukey[,'diff'] & tukey[,'upr']>tukey[,'diff']) && all(tukey[,'p adj']>=0 & tukey[,'p adj']<=1))
fac<-expand.grid(A=c('A0','A1'),B=c('B0','B1'),replicate=1:20)
fac$id<-seq_len(nrow(fac))
fac$y<-ifelse((fac$A=='A1')==(fac$B=='B1'),2,-2)+rnorm(nrow(fac),0,0.3)
fit<-bf_two_factor_model(fac,'y',c('A','B'),'id')
it<-bf_two_factor_interaction(fit,c('A','B'))
check(it$p_raw<1e-10 && it$df_numerator==1 && is.finite(it$statistic))
check(rejected(bf_two_factor_model(fac[!(fac$A=='A1' & fac$B=='B1'),],'y',c('A','B'),'id')))
p<-bf_adjust_contrasts(data.frame(p_raw=c(.01,.04,.2,.005)),'holm','all_planned')
check(max(abs(p$p_adj-c(.03,.08,.2,.02)))<1e-12)
check(rejected(bf_adjust_contrasts(p,'holm','all_planned')))
check(rejected(bf_adjust_contrasts(data.frame(p_raw=c(.01,NA)),'holm','all_planned')))
if (!requireNamespace('emmeans',quietly=TRUE)) stop('emmeans is required to verify the simple-effect recipe')
emm<-emmeans::emmeans(fit,~ A | B)
con<-emmeans::contrast(emm,method='pairwise',adjust='none')
tab<-as.data.frame(summary(con,by=NULL,infer=c(TRUE,TRUE),adjust='none'))
names(tab)[names(tab)=='p.value']<-'p_raw'
combined<-bf_adjust_contrasts(tab,'holm','A_within_all_B')
check(nrow(combined)==2 && all(combined$p_adj>=combined$p_raw) && all(combined$lower.CL<combined$estimate & combined$upper.CL>combined$estimate))
check(sign(combined$estimate[1])!=sign(combined$estimate[2]))
constant<-data.frame(id=1:8,g=rep(c('A','B'),each=4),y=rep(1,8))
check(rejected(bf_oneway_test(constant,'y','g','id','welch')))
cat(sprintf('STATISTICS_HELPERS_OK: %d checks; numerical/guard tests only, not scientific or visual benchmark\n',checks))
